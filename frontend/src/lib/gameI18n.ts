export function getHubStrings(locale: string): HubLocalizedStrings {
  const normLocale = (locale.split("-")[0].toLowerCase() as SupportedLocale) || "en";
  if (HUB_I18N_STRINGS[normLocale]) return HUB_I18N_STRINGS[normLocale];
  if (normLocale === "as" && HUB_I18N_STRINGS.bn) return HUB_I18N_STRINGS.bn;
  if (normLocale === "bn" && HUB_I18N_STRINGS.as) return HUB_I18N_STRINGS.as;
  if ((normLocale === "mr" || normLocale === "ne" || normLocale === "brx") && HUB_I18N_STRINGS.hi) return HUB_I18N_STRINGS.hi;
  if (normLocale === "mni" && (HUB_I18N_STRINGS.as || HUB_I18N_STRINGS.bn)) return (HUB_I18N_STRINGS.as || HUB_I18N_STRINGS.bn);
  return HUB_I18N_STRINGS.en;
}


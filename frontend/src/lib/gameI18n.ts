export function getGameStrings(gameId: string, locale: string): GameLocalizedStrings {
  const normLocale = (locale.split("-")[0].toLowerCase() as SupportedLocale) || "en";
  const gameStrings = GAME_I18N_STRINGS[gameId];

  // 1. Direct match
  if (gameStrings && gameStrings[normLocale]) {
    return gameStrings[normLocale]!;
  }

  // 2. Linguistic cousin fallbacks
  if (normLocale === "as" && (gameStrings?.bn || gameStrings?.hi)) return (gameStrings.bn || gameStrings.hi)!;
  if (normLocale === "bn" && (gameStrings?.as || gameStrings?.hi)) return (gameStrings.as || gameStrings.hi)!;
  if ((normLocale === "mr" || normLocale === "ne" || normLocale === "brx") && gameStrings?.hi) return gameStrings.hi;
  if (normLocale === "mni" && (gameStrings?.as || gameStrings?.bn || gameStrings?.hi)) return (gameStrings.as || gameStrings.bn || gameStrings.hi)!;

  // 3. If a regional language was chosen (Garo, Khasi, Mizo, etc.), prioritize the 11-Language Regional Definition over English!
  if (normLocale !== "en" && UNIVERSAL_11_LANG_DESCRIPTIONS[normLocale]) {
    return UNIVERSAL_11_LANG_DESCRIPTIONS[normLocale];
  }

  // 4. Game English fallback
  if (gameStrings && gameStrings.en) {
    return gameStrings.en;
  }

  // 5. English Default
  return UNIVERSAL_11_LANG_DESCRIPTIONS.en;
}

